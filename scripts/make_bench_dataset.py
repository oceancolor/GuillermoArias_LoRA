"""Generate a SYNTHETIC 1024px image set for the 200-step s/it benchmark ONLY.

Why this exists
---------------
The 10-hour schedule in 本机训练评估与成本.md is anchored on a *measured*
seconds/iteration, but S0 (real image collection + captioning) takes hours of
human work. This generator decouples the two: with latent and text-encoder
outputs cached to disk, each training step's cost depends only on the
resolution bucket, not on image content. A synthetic 1024px set therefore gives
a valid s/it estimate before any real data exists.

NEVER train a real LoRA on this output. It contains no style signal.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

from PIL import Image, ImageDraw

DEFAULT_CAPTION = (
    "mdtr_style, a woman reading a book on a seaside terrace, striped chair, "
    "potted plant, white wall, strong sunlight from the left"
)

TOML_TEMPLATE = """# SYNTHETIC benchmark dataset - DO NOT USE FOR REAL TRAINING
# Generated by scripts/make_bench_dataset.py; image_dir points at fake 1024px
# images. Use it only with BENCH=1 to measure seconds/iteration.
[general]
shuffle_caption = false
caption_extension = ".txt"
keep_tokens = 1

[[datasets]]
resolution = 1024
batch_size = 1
enable_bucket = true
min_bucket_reso = 768
max_bucket_reso = 1280
bucket_reso_steps = 32
bucket_no_upscale = true

  [[datasets.subsets]]
  image_dir = "{image_dir}"
  num_repeats = 4
"""


def make_image(size: int, seed: int) -> Image.Image:
    """Flat colour blocks + directional strokes: cheap, reproducible, decodable."""
    rng = random.Random(seed)
    im = Image.new("RGB", (size, size), (214, 202, 178))
    dr = ImageDraw.Draw(im)
    step = size // 8
    for y in range(0, size, step):
        for x in range(0, size, step):
            c = (
                min(255, 110 + rng.randint(0, 110)),
                min(255, 120 + rng.randint(0, 100)),
                min(255, 135 + rng.randint(0, 90)),
            )
            dr.rectangle([x, y, x + step - 1, y + step - 1], fill=c)
    for _ in range(size // 3):
        x, y = rng.randint(0, size - 40), rng.randint(0, size - 10)
        dr.line(
            [x, y, x + rng.randint(6, 34), y + rng.randint(-8, 8)],
            fill=(236, 224, 198),
            width=2,
        )
    return im


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="E:/lora_local/bench/10_mdtr",
                    help="output image directory (default: E:/lora_local/bench/10_mdtr)")
    ap.add_argument("--count", type=int, default=8)
    ap.add_argument("--size", type=int, default=1024)
    ap.add_argument("--caption", default=DEFAULT_CAPTION)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--toml", default=None,
                    help="also write a matching kohya TOML to this path")
    ap.add_argument("--force", action="store_true",
                    help="allow overwriting an existing non-empty image dir")
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    existing = list(out.glob("*.png")) + list(out.glob("*.jpg"))
    if existing and not args.force:
        print(f"[ABORT] {out} already has {len(existing)} images. "
              "Use a fresh --out dir or pass --force.")
        return 1
    if args.count < 1 or args.size < 256:
        print("[ABORT] --count must be >= 1 and --size >= 256")
        return 1

    for i in range(args.count):
        stem = f"bench_{i:03d}"
        make_image(args.size, args.seed + i).save(out / f"{stem}.png")
        (out / f"{stem}.txt").write_text(args.caption, encoding="utf-8")

    marker = out / "_SYNTHETIC_BENCH_ONLY.txt"
    marker.write_text(
        "Synthetic images for the 200-step s/it benchmark.\n"
        "NO style signal. NEVER use for real LoRA training.\n",
        encoding="utf-8",
    )

    if args.toml:
        toml_path = Path(args.toml)
        toml_path.parent.mkdir(parents=True, exist_ok=True)
        toml_path.write_text(
            TOML_TEMPLATE.format(image_dir=out.as_posix()), encoding="utf-8"
        )
        print(f"[ok] wrote TOML: {toml_path} -> {out.as_posix()}")

    print(f"[ok] {args.count} synthetic {args.size}x{args.size} images + captions -> {out}")
    print("[!] BENCHMARK ONLY - these images contain no style information.")
    print("    Next: BENCH=1 DATASET_CONFIG=configs/dataset_local_bench.toml "
          "bash scripts/train_local_sdxl.sh")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
